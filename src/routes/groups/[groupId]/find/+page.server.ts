import { error, redirect } from "@sveltejs/kit";
import { z } from "zod";

import { db } from "#lib/server/db/index.ts";
import { readForm } from "#lib/server/forms.ts";
import { getGroupForMember } from "#lib/server/groups.ts";
import { requireUser } from "#lib/server/require-user.ts";
import { watchRefusal } from "#lib/server/watch-session-forms.ts";
import {
  getActiveWatchSessionId,
  getWatchSession,
  listParticipants,
  startWatchSession,
} from "#lib/server/watch-sessions.ts";
import { watchFiltersSchema } from "#lib/watch-fields.ts";

import type { Actions, PageServerLoad } from "./$types";

// The start screen. `?replace=<session ID>` is "Start a new one": the form
// starts out with that session's filters and people, and starting closes it
// (its matches are saved). Change filters keeps the session instead
// (/sessions/<id>/filters).
export const load: PageServerLoad = async ({ params, locals, url }) => {
  const user = requireUser(locals);
  const groupId = z.uuid().safeParse(params.groupId);
  const group = groupId.success
    ? await getGroupForMember(db, groupId.data, user.id)
    : null;
  if (group === null) error(404, "Group not found.");

  const activeId = await getActiveWatchSessionId(db, group.id);
  const active =
    activeId === null ? null : await getWatchSession(db, activeId, user.id);
  const isHost = active?.participation?.role === "host";
  // Only the active session's host can replace it; anything else in the URL
  // (an old link, a session that has ended) is ignored.
  const replaceParam = z.uuid().safeParse(url.searchParams.get("replace"));
  const replacing =
    isHost && replaceParam.success && replaceParam.data === activeId
      ? active
      : null;

  // Everyone else in the group, to pick who's watching. A new session
  // starts with all of them ticked (the usual movie night); starting over
  // starts with the current session's people.
  const others = group.members.filter((member) => member.userId !== user.id);
  const invited =
    replacing === null
      ? others.map((member) => member.userId)
      : (await listParticipants(db, replacing.id))
          .filter((person) => person.role !== "host")
          .map((person) => person.userId);

  return {
    group: { id: group.id, name: group.name },
    members: others.map(({ userId, nickname }) => ({ userId, nickname })),
    invited,
    genres: await db.query.genres.findMany({ orderBy: { name: "asc" } }),
    active:
      active === null
        ? null
        : {
            id: active.id,
            isHost,
            // Someone else's session you're in or invited to: go there.
            isMine: active.participation !== null || active.invitation !== null,
          },
    replacing:
      replacing === null
        ? null
        : {
            id: replacing.id,
            filters: {
              maxRuntime: replacing.maxRuntime,
              minYear: replacing.minYear,
              maxYear: replacing.maxYear,
              genreIds: replacing.genreIds,
            },
          },
  };
};

const startSchema = z
  .object({
    actionId: z.uuid(),
    // Generated by the browser with the action ID (ActionForm's newIds), so a
    // retried start lands on the same session.
    watchSessionId: z.uuid(),
    // The active session this start replaces ("Start a new one"), if any.
    replace: z.union([z.literal(""), z.uuid()]).default(""),
    // One checkbox per member, so nothing, one value, or a list. The server
    // checks they're members; Better Auth's IDs are letters and digits.
    invitedUserIds: z
      .union([z.string(), z.array(z.string())])
      .default([])
      .transform((value) => (Array.isArray(value) ? value : [value]))
      .pipe(z.array(z.string().regex(/^[\w-]{1,64}$/)).max(100)),
  })
  .and(watchFiltersSchema);

export const actions = {
  start: async ({ request, locals, params }) => {
    const user = requireUser(locals);
    const groupId = z.uuid().safeParse(params.groupId);
    if (!groupId.success) error(404, "Group not found.");
    const form = await readForm(request, startSchema);
    if (!form.ok) return form.failure;

    const { actionId, watchSessionId, replace, invitedUserIds, ...filters } =
      form.data;
    const outcome = await startWatchSession(db, {
      actionId,
      userId: user.id,
      groupId: groupId.data,
      watchSessionId,
      filters,
      replacedWatchSessionId: replace === "" ? null : replace,
      invitedUserIds,
    });
    // Someone in the group started one first (both saw "Find a movie"):
    // reload this page, which now shows the session that's going.
    if (outcome === "session_active") {
      redirect(303, `/groups/${groupId.data}/find`);
    }
    const failed = watchRefusal(outcome);
    if (failed !== null) return failed;
    redirect(303, `/sessions/${watchSessionId}`);
  },
} satisfies Actions;
