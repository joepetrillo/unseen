interface Change {
  /** Generated by the browser, so a retried request carries the same ID. */
  actionId: string;
  /** The acting user, from the login session. */
  userId: string;
}

/**
 * Starts a session in a group, with the user as host and only active
 * participant. `invitedUserIds` (other group members, "who's watching
 * tonight") get invited participations: they count once they accept
 * (joinWatchSession). When the start replaces a session, invitees who were
 * participating in it join right away. The browser picks the session's ID, so a retried start
 * lands on the same session. If the group already has an active session, the
 * start must name it in `replacedWatchSessionId` (Change filters): it's
 * closed in the same transaction, recording its matches.
 */
export function startWatchSession(
  db: Db,
  change: Change & {
    groupId: string;
    watchSessionId: string;
    filters: WatchFilters;
    replacedWatchSessionId: string | null;
    invitedUserIds: readonly string[];
  }
): Promise<WatchSessionOutcome> {
  const { actionId, userId, groupId, watchSessionId, filters } = change;
  const { replacedWatchSessionId } = change;
  // Sorted and without duplicates (or the host), so a retry compares equal.
  const invitedUserIds = [...new Set(change.invitedUserIds)]
    .filter((id) => id !== userId)
    .sort();
  const action: Action = {
    id: actionId,
    userId,
    type: "watch_session_start",
    groupId,
    watchSessionId,
    ...filters,
    replacedWatchSessionId,
    invitedUserIds,
  };
  return runWatchAction(db, action, async (tx) => {
    // People already in the session being replaced (Change filters): they
    // agreed to watch tonight, so they stay in without accepting again.
    let carriedOver = new Set<string>();
    // The group's row lock queues starts in one group, so two can't both
    // see "no active session". The partial unique index backs it up.
    const [group] = await tx
      .select({ id: groups.id })
      .from(groups)
      .where(eq(groups.id, groupId))
      .for("update");
    const member =
      group === undefined
        ? undefined
        : await tx.query.groupMembers.findFirst({
            columns: { userId: true },
            where: { groupId, userId },
          });
    if (member === undefined) throw new Refusal("not_found");

    const [active] = await tx
      .select({ id: watchSessions.id })
      .from(watchSessions)
      .where(
        and(eq(watchSessions.groupId, groupId), isNull(watchSessions.closedAt))
      )
      .for("update");
    if (active !== undefined) {
      // Named explicitly, so a stale start screen can't end a newer session.
      if (active.id !== replacedWatchSessionId) {
        throw new Refusal("session_active");
      }
      await requireHost(tx, active.id, userId);
      carriedOver = await activeUserIds(tx, active.id);
      await closeWatchSession(tx, active.id, groupId);
    }

    const created = await tx
      .insert(watchSessions)
      .values({ id: watchSessionId, groupId, ...filters })
      .onConflictDoNothing({ target: watchSessions.id })
      .returning({ id: watchSessions.id });
    // Another action already used this session ID: a bug or a tampered
    // request, never a retry (that would share the action ID).
    if (created.length === 0) throw new Refusal("conflict");
    await tx.insert(participants).values({
      watchSessionId,
      userId,
      role: "host",
      joinedAt: sql`now()`,
    });

    if (invitedUserIds.length > 0) {
      // Only current members can be invited. Membership changes take the
      // group's row lock, which this transaction holds, so it can't change
      // between this check and the insert.
      const members = await tx
        .select({ userId: groupMembers.userId })
        .from(groupMembers)
        .where(
          and(
            eq(groupMembers.groupId, groupId),
            inArray(groupMembers.userId, invitedUserIds)
          )
        );
      if (members.length !== invitedUserIds.length) {
        throw new Refusal("not_found");
      }
      // A null joined_at means invited: not participating until they accept.
      await tx.insert(participants).values(
        invitedUserIds.map((id) => ({
          watchSessionId,
          userId: id,
          role: "guest" as const,
          joinedAt: carriedOver.has(id) ? sql`now()` : null,
        }))
      );
    }
  });
}

/**
 * Accepts an invitation: the participation becomes active, so the person's
 * answers and seen list count from now on. Accepting one that's already
 * active (from another device) changes nothing.
 */
export function joinWatchSession(
  db: Db,
  change: Change & { watchSessionId: string; participationId: string }
): Promise<WatchSessionOutcome> {
  const { actionId, userId, watchSessionId, participationId } = change;
  const action: Action = {
    id: actionId,
    userId,
    type: "watch_session_join",
    watchSessionId,
    participationId,
  };
  return runWatchAction(db, action, async (tx) => {
    const row = await lockOwnParticipation(
      tx,
      participationId,
      userId,
      watchSessionId
    );
    if (row.removedAt !== null) throw new Refusal("not_participating");
    if (row.closedAt !== null) throw new Refusal("session_closed");
    if (row.joinedAt !== null) return;
    await tx
      .update(participants)
      .set({ joinedAt: sql`now()` })
      .where(eq(participants.id, participationId));
    await notifyWatchSessionChanged(tx, watchSessionId);
  });
}

/**
 * Host only: Change filters. The session, its people, and its answers stay,
 * so its matches do too (they come from answers, never from filters); only
 * the movies dealt from now on change. Cards already on screen stay.
 */
export function changeWatchSessionFilters(
  db: Db,
  change: Change & { watchSessionId: string; filters: WatchFilters }
): Promise<WatchSessionOutcome> {
  const { actionId, userId, watchSessionId, filters } = change;
  const action: Action = {
    id: actionId,
    userId,
    type: "watch_session_filters",
    watchSessionId,
    ...filters,
  };
  return runWatchAction(db, action, async (tx) => {
    const session = await lockSessionForMember(tx, watchSessionId, userId);
    if (session.closedAt !== null) throw new Refusal("session_closed");
    await requireHost(tx, watchSessionId, userId);
    await tx
      .update(watchSessions)
      .set(filters)
      .where(eq(watchSessions.id, watchSessionId));
    await notifyWatchSessionChanged(tx, watchSessionId);
  });
}

/** Host only. Records the session's current matches as past matches. */
export function endWatchSession(
  db: Db,
  change: Change & { watchSessionId: string }
): Promise<WatchSessionOutcome> {
  const { actionId, userId, watchSessionId } = change;
  const action: Action = {
    id: actionId,
    userId,
    type: "watch_session_end",
    watchSessionId,
  };
  return runWatchAction(db, action, async (tx) => {
    const session = await lockSessionForMember(tx, watchSessionId, userId);
    if (session.closedAt !== null) throw new Refusal("session_closed");
    await requireHost(tx, watchSessionId, userId);
    await closeWatchSession(tx, watchSessionId, session.groupId);
  });
}

/**
 * Records an answer. Seen also puts the movie on the user's seen list (and
 * replaces an earlier Not seen: "Actually, I've seen this"). A Not seen on a
 * movie someone has seen is still recorded: it can't match, but Undo takes
 * it back like any other answer, and it counts if they withdraw their Seen.
 */
export function answerMovie(
  db: Db,
  change: Change & {
    /** The session the request is about (the page's URL). */
    watchSessionId: string;
    participationId: string;
    movieId: number;
    answer: "seen" | "not_seen";
  }
): Promise<WatchSessionOutcome> {
  const { actionId, userId, watchSessionId, participationId, movieId } = change;
  const { answer } = change;
  const action: Action = {
    id: actionId,
    userId,
    type: answer === "seen" ? "watch_answer_seen" : "watch_answer_not_seen",
    participationId,
    movieId,
  };
  return runWatchAction(db, action, async (tx) => {
    await lockParticipation(tx, participationId, userId, watchSessionId);
    if (answer === "seen") {
      await setAnswer(tx, participationId, movieId, "seen");
      await confirmSeen(tx, { actionId, userId, movieId });
    } else {
      await setAnswer(tx, participationId, movieId, "not_seen");
    }
    await notifyWatchSessionChanged(tx, watchSessionId);
  });
}

/**
 * Undoes the participation's latest answer that isn't undone yet. Each
 * person has their own stack per session; repeated undos step back through
 * it. Undoing a Seen removes the seen-list entry only if this answer is
 * still its latest confirmation (see withdrawSeen). The answer before it,
 * if any (the Not seen that "Actually, I've seen this" replaced), counts
 * again. Returns the undone movie, so the screen can show it again; a
 * retried undo returns the same one.
 */
export async function undoLastAnswer(
  db: Db,
  change: Change & { watchSessionId: string; participationId: string }
): Promise<{ outcome: WatchSessionOutcome; movieId: number | null }> {
  const { actionId, userId, watchSessionId, participationId } = change;
  const action: Action = {
    id: actionId,
    userId,
    type: "watch_answer_undo",
    participationId,
  };
  const outcome = await runWatchAction(db, action, async (tx) => {
    await lockParticipation(tx, participationId, userId, watchSessionId);
    const [last] = await latestAnswers(tx, participationId).limit(1);
    if (last?.movieId == null) throw new Refusal("nothing_to_undo");
    const { movieId } = last;

    await markUndone(tx, last.id, actionId);
    if (last.type === "watch_answer_seen") {
      await withdrawSeen(tx, { actionId: last.id, userId, movieId });
    }
    const [previous] = await latestAnswers(tx, participationId, movieId).limit(
      1
    );
    if (previous === undefined) {
      await tx
        .delete(answers)
        .where(
          and(
            eq(answers.participationId, participationId),
            eq(answers.movieId, movieId)
          )
        );
    } else if (previous.type === "watch_answer_seen") {
      // Back to the state right after that Seen, seen-list entry included.
      await setAnswer(tx, participationId, movieId, "seen");
      await confirmSeen(tx, { actionId: previous.id, userId, movieId });
    } else {
      await setAnswer(tx, participationId, movieId, "not_seen");
    }
    await notifyWatchSessionChanged(tx, watchSessionId);
  });

  const [undone] = await db
    .select({ movieId: actions.movieId })
    .from(actions)
    .where(eq(actions.undoneByActionId, actionId))
    .limit(1);
  return { outcome, movieId: undone?.movieId ?? null };
}

/**
 * The live-update seam (spec section 5): every change to a session calls
 * this, in its transaction. Bumps the revision polling compares (stage 7)
 * and the activity time auto-close reads (stage 8).
 */
export async function notifyWatchSessionChanged(
  tx: Transaction,
  watchSessionId: string
): Promise<void> {
  await tx
    .update(watchSessions)
    .set({
      revision: sql`${watchSessions.revision} + 1`,
      lastActivityAt: sql`now()`,
    })
    .where(eq(watchSessions.id, watchSessionId));
}

