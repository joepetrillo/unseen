/**
 * The session as one of its group's members sees it, or null when the user
 * isn't in the group (or it doesn't exist): pages answer both with a 404.
 * `participation` is the user's active participation, if any.
 */
export async function getWatchSession(
  db: Db,
  watchSessionId: string,
  userId: string
) {
  const [session] = await db
    .select({
      id: watchSessions.id,
      groupId: watchSessions.groupId,
      groupName: groups.name,
      maxRuntime: watchSessions.maxRuntime,
      minYear: watchSessions.minYear,
      maxYear: watchSessions.maxYear,
      genreIds: watchSessions.genreIds,
      closedAt: watchSessions.closedAt,
    })
    .from(watchSessions)
    .innerJoin(groups, eq(groups.id, watchSessions.groupId))
    .innerJoin(
      groupMembers,
      and(
        eq(groupMembers.groupId, watchSessions.groupId),
        eq(groupMembers.userId, userId)
      )
    )
    .where(eq(watchSessions.id, watchSessionId));
  if (session === undefined) return null;

  const [participation] = await db
    .select({ id: participants.id, role: participants.role })
    .from(participants)
    .where(and(activeIn(watchSessionId), eq(participants.userId, userId)));
  return { ...session, participation: participation ?? null };
}

/** The group's active session, if any. */
export async function getActiveWatchSessionId(
  db: Db,
  groupId: string
): Promise<string | null> {
  const [active] = await db
    .select({ id: watchSessions.id })
    .from(watchSessions)
    .where(
      and(eq(watchSessions.groupId, groupId), isNull(watchSessions.closedAt))
    );
  return active?.id ?? null;
}

/**
 * The next cards for a participation: the top eligible movies it hasn't
 * answered, skipping `exclude` (cards already on screen or waiting to save).
 * No cursor or offset: rankings shift as people answer, so each request asks
 * for the current top.
 *
 * Eligible: enough votes, released in the US, inside the session's filters,
 * and on no participant's seen list (a Seen answer always puts it there).
 * Ranked: previously matched last, then most Not seen answers from others,
 * then TMDB vote count, then movie ID.
 */
export async function dealCards(
  db: Db,
  {
    watchSessionId,
    participationId,
    exclude = [],
    limit = DEAL_SIZE,
  }: {
    watchSessionId: string;
    participationId: string;
    exclude?: readonly number[];
    limit?: number;
  }
): Promise<MovieCard[]> {
  const [session] = await db
    .select({
      groupId: watchSessions.groupId,
      maxRuntime: watchSessions.maxRuntime,
      minYear: watchSessions.minYear,
      maxYear: watchSessions.maxYear,
      genreIds: watchSessions.genreIds,
    })
    .from(watchSessions)
    .where(eq(watchSessions.id, watchSessionId));
  if (session === undefined) return [];
  const { groupId, maxRuntime, minYear, maxYear, genreIds } = session;

  // Matches recorded when one of the group's sessions closed, up to the
  // moment this one started. Compared in SQL: Change filters closes the old
  // session and starts this one in one transaction, so they share a
  // timestamp, and a JavaScript Date would drop its microseconds.
  const previouslyMatched = sql<boolean>`exists (
    select 1 from ${groupPastMatches}
    where ${groupPastMatches.groupId} = ${groupId}
      and ${groupPastMatches.movieId} = ${movies.id}
      and ${groupPastMatches.recordedAt} <= (
        select ${watchSessions.createdAt} from ${watchSessions}
        where ${watchSessions.id} = ${watchSessionId}
      )
  )`;
  // "Finish what's started": others' Not seen answers on this movie.
  const confirmations = sql<number>`(
    select count(*) from ${answers}
    join ${participants} on ${participants.id} = ${answers.participationId}
    where ${activeIn(watchSessionId)}
      and ${participants.id} <> ${participationId}
      and ${answers.movieId} = ${movies.id}
      and ${answers.answer} = 'not_seen'
  )`.mapWith(Number);

  const rows = await db
    .select({
      id: movies.id,
      title: movies.title,
      year: sql<number | null>`extract(year from ${movies.releaseDate})::int`,
      runtime: movies.runtime,
      posterPath: movies.posterPath,
    })
    .from(movies)
    .where(
      and(
        gte(movies.voteCount, VOTE_COUNT_FLOOR),
        isNotNull(movies.usReleaseDate),
        lte(movies.usReleaseDate, sql`current_date`),
        // A missing runtime or year fails these comparisons, so such movies
        // are left out only while that filter is on.
        maxRuntime === null ? undefined : lte(movies.runtime, maxRuntime),
        minYear === null
          ? undefined
          : gte(movies.releaseDate, `${String(minYear)}-01-01`),
        maxYear === null
          ? undefined
          : lt(movies.releaseDate, `${String(maxYear + 1)}-01-01`),
        genreIds.length === 0
          ? undefined
          : inArray(
              movies.id,
              db
                .select({ id: movieGenres.movieId })
                .from(movieGenres)
                .where(inArray(movieGenres.genreId, genreIds))
            ),
        notExists(
          db
            .select({ one: sql`1` })
            .from(seenMovies)
            .innerJoin(participants, eq(participants.userId, seenMovies.userId))
            .where(
              and(activeIn(watchSessionId), eq(seenMovies.movieId, movies.id))
            )
        ),
        notExists(
          db
            .select({ one: sql`1` })
            .from(answers)
            .where(
              and(
                eq(answers.participationId, participationId),
                eq(answers.movieId, movies.id)
              )
            )
        ),
        exclude.length === 0 ? undefined : notInArray(movies.id, [...exclude])
      )
    )
    .orderBy(
      asc(previouslyMatched),
      desc(confirmations),
      desc(movies.voteCount),
      asc(movies.id)
    )
    .limit(limit);
  return withGenres(db, rows);
}

/**
 * The shortlist: movies every active participant answered Not seen and none
 * has on their seen list, in the order they became matches. Derived from
 * answers only, so filters and catalog changes never affect it.
 */
export async function listMatches(
  db: Db | Transaction,
  watchSessionId: string
): Promise<MovieCard[]> {
  const matched = matchedMovies(db, watchSessionId).as("matched");
  const rows = await db
    .select({
      id: movies.id,
      title: movies.title,
      year: sql<number | null>`extract(year from ${movies.releaseDate})::int`,
      runtime: movies.runtime,
      posterPath: movies.posterPath,
    })
    .from(matched)
    .innerJoin(movies, eq(movies.id, matched.movieId))
    .orderBy(asc(matched.matchedAt), asc(movies.id));
  return withGenres(db, rows);
}

/** One movie as a card (an undone answer's movie, shown again). */
export async function getCard(
  db: Db,
  movieId: number
): Promise<MovieCard | null> {
  const rows = await db
    .select({
      id: movies.id,
      title: movies.title,
      year: sql<number | null>`extract(year from ${movies.releaseDate})::int`,
      runtime: movies.runtime,
      posterPath: movies.posterPath,
    })
    .from(movies)
    .where(eq(movies.id, movieId));
  const [card] = await withGenres(db, rows);
  return card ?? null;
}

/** Whether the participation has an answer left to undo. */
export async function canUndo(
  db: Db,
  participationId: string
): Promise<boolean> {
  const [last] = await latestAnswers(db, participationId).limit(1);
  return last !== undefined;
}

