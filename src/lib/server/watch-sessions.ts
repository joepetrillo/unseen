// The only module that changes watch sessions, their participants, answers,
// and the group's past matches. Every change is an action (applied at most
// once per action ID, see actions.ts) and locks the session's row (a start
// locks the group's), so changes to one session run one at a time. Each
// change ends with notifyWatchSessionChanged, which bumps the revision that
// polling (stage 7) watches.
//
// Callers pass inputs that already passed #lib/watch-fields.ts; this module
// checks permissions, which depend on the database.

/** Movies with fewer TMDB votes are too obscure to deal. Revisit in stage 9. */
export const VOTE_COUNT_FLOOR = 200;
/** How many cards one request deals: the visible card plus a small queue. */
export const DEAL_SIZE = 6;

/**
 * Why a change was refused (nothing changed, nothing was logged):
 * - `not_found`: no such session or participation, or it isn't yours. One
 *   answer for both, like groups, so IDs reveal nothing.
 * - `not_host`: only the host can do this.
 * - `session_active`: the group already has an active session, and the start
 *   didn't name it as the one to replace.
 * - `session_closed`: closed sessions reject all changes.
 * - `not_participating`: this participation was removed (or never joined).
 * - `movie_not_found`: no such movie in the catalog.
 * - `nothing_to_undo`: no answer left on your undo stack.
 */
export type WatchSessionRefusal =
  | "not_found"
  | "not_host"
  | "session_active"
  | "session_closed"
  | "not_participating"
  | "movie_not_found"
  | "nothing_to_undo";

export type WatchSessionOutcome = ActionOutcome | WatchSessionRefusal;

// Thrown inside a transaction to roll it back, action log entry included, so
// a retry after the situation changes runs normally (like groups.ts).
class Refusal extends Error {
  constructor(readonly reason: WatchSessionRefusal | "conflict") {
    super(reason);
  }
}

async function runWatchAction(
  db: Db,
  action: Action,
  apply: (tx: Transaction) => Promise<void>
): Promise<WatchSessionOutcome> {
  try {
    return await runAction(db, action, apply);
  } catch (error) {
    if (error instanceof Refusal) return error.reason;
    // The log's movie_id has a foreign key, checked as the action is logged:
    // a movie not in the catalog fails there, before the change runs.
    if (
      error instanceof DrizzleQueryError &&
      error.cause instanceof DatabaseError &&
      error.cause.code === "23503" &&
      error.cause.constraint === "actions_movie_id_movies_id_fkey"
    ) {
      return "movie_not_found";
    }
    throw error;
  }
}

