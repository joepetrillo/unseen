// Helpers

// Movies matched in the session, each with when it became a match (its last
// Not seen). A Seen answer always puts the movie on a seen list, so checking
// seen lists also covers Seen answers.
function matchedMovies(db: Db | Transaction, watchSessionId: string) {
  return db
    .select({
      movieId: answers.movieId,
      matchedAt: sql<Date>`max(${answers.answeredAt})`.as("matched_at"),
    })
    .from(answers)
    .innerJoin(participants, eq(participants.id, answers.participationId))
    .where(and(activeIn(watchSessionId), eq(answers.answer, "not_seen")))
    .groupBy(answers.movieId)
    .having(
      and(
        sql`count(*) = (
          select count(*) from ${participants} where ${activeIn(watchSessionId)}
        )`,
        notExists(
          db
            .select({ one: sql`1` })
            .from(seenMovies)
            .innerJoin(participants, eq(participants.userId, seenMovies.userId))
            .where(
              and(
                activeIn(watchSessionId),
                eq(seenMovies.movieId, answers.movieId)
              )
            )
        )
      )
    );
}

// The participation's answers not undone yet, newest first (its undo stack),
// optionally for one movie.
function latestAnswers(
  db: Db | Transaction,
  participationId: string,
  movieId?: number
) {
  return db
    .select({ id: actions.id, type: actions.type, movieId: actions.movieId })
    .from(actions)
    .where(
      and(
        eq(actions.participationId, participationId),
        inArray(actions.type, [...ANSWER_TYPES]),
        isNull(actions.undoneByActionId),
        movieId === undefined ? undefined : eq(actions.movieId, movieId)
      )
    )
    .orderBy(desc(actions.createdAt), desc(actions.id))
    .$dynamic();
}

async function withGenres(
  db: Db | Transaction,
  rows: Omit<MovieCard, "genres">[]
): Promise<MovieCard[]> {
  if (rows.length === 0) return [];
  const links = await db
    .select({ movieId: movieGenres.movieId, name: genres.name })
    .from(movieGenres)
    .innerJoin(genres, eq(genres.id, movieGenres.genreId))
    .where(
      inArray(
        movieGenres.movieId,
        rows.map((row) => row.id)
      )
    )
    .orderBy(asc(genres.name));
  return rows.map((row) => ({
    ...row,
    genres: links
      .filter((link) => link.movieId === row.id)
      .map((link) => link.name),
  }));
}

async function setAnswer(
  tx: Transaction,
  participationId: string,
  movieId: number,
  answer: "seen" | "not_seen"
): Promise<void> {
  await tx
    .insert(answers)
    .values({ participationId, movieId, answer })
    .onConflictDoUpdate({
      target: [answers.participationId, answers.movieId],
      set: { answer, answeredAt: sql`now()` },
    });
}

// Whether any active participant has the movie on their seen list.
async function seenBySomeone(
  tx: Transaction,
  watchSessionId: string,
  movieId: number
): Promise<boolean> {
  const [row] = await tx
    .select({ one: sql`1` })
    .from(seenMovies)
    .innerJoin(participants, eq(participants.userId, seenMovies.userId))
    .where(and(activeIn(watchSessionId), eq(seenMovies.movieId, movieId)))
    .limit(1);
  return row !== undefined;
}

/**
 * Locks the session's row until the transaction ends, if the user is in its
 * group. Every change to a session takes this lock, so they queue.
 */
async function lockSessionForMember(
  tx: Transaction,
  watchSessionId: string,
  userId: string
): Promise<{ groupId: string; closedAt: Date | null }> {
  const [session] = await tx
    .select({
      groupId: watchSessions.groupId,
      closedAt: watchSessions.closedAt,
    })
    .from(watchSessions)
    .innerJoin(
      groupMembers,
      and(
        eq(groupMembers.groupId, watchSessions.groupId),
        eq(groupMembers.userId, userId)
      )
    )
    .where(eq(watchSessions.id, watchSessionId))
    .for("update", { of: watchSessions });
  if (session === undefined) throw new Refusal("not_found");
  return session;
}

/**
 * The checks for answering and undoing: the participation is the user's,
 * belongs to the session the request names, is still active, and the
 * session is still open. Locks the session's row.
 */
async function lockParticipation(
  tx: Transaction,
  participationId: string,
  userId: string,
  watchSessionId: string
): Promise<void> {
  const row = await lockOwnParticipation(
    tx,
    participationId,
    userId,
    watchSessionId
  );
  if (row.joinedAt === null || row.removedAt !== null) {
    throw new Refusal("not_participating");
  }
  if (row.closedAt !== null) throw new Refusal("session_closed");
}

// The user's participation in the session the request names, with the
// session's row locked. Callers check its status.
async function lockOwnParticipation(
  tx: Transaction,
  participationId: string,
  userId: string,
  watchSessionId: string
): Promise<{
  joinedAt: Date | null;
  removedAt: Date | null;
  closedAt: Date | null;
}> {
  const [row] = await tx
    .select({
      watchSessionId: participants.watchSessionId,
      userId: participants.userId,
      joinedAt: participants.joinedAt,
      removedAt: participants.removedAt,
      closedAt: watchSessions.closedAt,
    })
    .from(participants)
    .innerJoin(watchSessions, eq(watchSessions.id, participants.watchSessionId))
    .where(eq(participants.id, participationId))
    .for("update", { of: watchSessions });
  // A participation from another session (a mismatched or crafted request)
  // gets the same answer as someone else's: the reply describes the
  // session in the URL, so the two must agree.
  if (row?.userId !== userId || row.watchSessionId !== watchSessionId) {
    throw new Refusal("not_found");
  }
  return row;
}

async function activeUserIds(
  tx: Transaction,
  watchSessionId: string
): Promise<Set<string>> {
  const rows = await tx
    .select({ userId: participants.userId })
    .from(participants)
    .where(activeIn(watchSessionId));
  return new Set(rows.map((row) => row.userId));
}

async function requireHost(
  tx: Transaction,
  watchSessionId: string,
  userId: string
): Promise<void> {
  const [me] = await tx
    .select({ role: participants.role })
    .from(participants)
    .where(and(activeIn(watchSessionId), eq(participants.userId, userId)));
  if (me?.role !== "host") throw new Refusal("not_host");
}

// Records what's a match right now as the group's past matches (the first
// record of a movie is kept), then closes the session.
async function closeWatchSession(
  tx: Transaction,
  watchSessionId: string,
  groupId: string
): Promise<void> {
  const matched = await matchedMovies(tx, watchSessionId);
  if (matched.length > 0) {
    await tx
      .insert(groupPastMatches)
      .values(matched.map(({ movieId }) => ({ groupId, movieId })))
      .onConflictDoNothing();
  }
  await tx
    .update(watchSessions)
    .set({ closedAt: sql`now()` })
    .where(eq(watchSessions.id, watchSessionId));
  await notifyWatchSessionChanged(tx, watchSessionId);
}
